/**
 * Test the PNG image loader with a static truecolor PNG image.
 */
static void testPngImgLoaderStatic()
{
    PngImgLoader       loader;
    YAGfxDynamicBitmap bitmap;
    FS                 fileSystem;
    uint16_t           x;
    uint16_t           y;

    TEST_ASSERT_EQUAL(PngImgLoader::RET_OK, loader.load(fileSystem, FILE_NAME_STATIC, bitmap));
    TEST_ASSERT_TRUE(bitmap.isAllocated());
    TEST_ASSERT_EQUAL_UINT16(EXPECTED_DATA_WIDTH, bitmap.getWidth());
    TEST_ASSERT_EQUAL_UINT16(EXPECTED_DATA_HEIGHT, bitmap.getHeight());

    for (y = 0U; y < EXPECTED_DATA_HEIGHT; ++y)
    {
        for (x = 0U; x < EXPECTED_DATA_WIDTH; ++x)
        {
            const uint32_t expected = EXPECTED_DATA[x + y * EXPECTED_DATA_WIDTH];
            const uint32_t actual   = static_cast<uint32_t>(bitmap.getColor(static_cast<int16_t>(x), static_cast<int16_t>(y)));

            TEST_ASSERT_EQUAL_UINT32(expected, actual);
        }
    }
}

