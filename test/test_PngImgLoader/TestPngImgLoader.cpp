/**
 * Description of a PNG file, which is generated by the test itself. Only the
 * chunks which the loader cares about are supported: IHDR, PLTE, tRNS, IDAT
 * and IEND.
 */
struct PngSpec
{
    uint32_t       width;       /**< Image width in pixels. */
    uint32_t       height;      /**< Image height in pixels. */
    uint8_t        bitDepth;    /**< Bits per sample. */
    uint8_t        colorType;   /**< PNG color type. */
    const uint8_t* palette;     /**< Palette (PLTE) colors as RGB triplets. May be nullptr. */
    size_t         paletteSize; /**< Size of the palette in bytes. */
    const uint8_t* trns;        /**< Transparency (tRNS) alpha values. May be nullptr. */
    size_t         trnsSize;    /**< Size of the transparency information in bytes. */
    const uint8_t* raw;         /**< Raw image data, every scanline prefixed by its filter byte. May be nullptr. */
    size_t         rawSize;     /**< Size of the raw image data in bytes. */
};

