/**
 * Test the PNG image loader at the limit of the decoder's internal line
 * buffer.
 *
 * PNGdec keeps the current and the previous de-filtered image line in one
 * buffer of PNG_MAX_BUFFERED_PIXELS (2562) bytes, but only refuses a line of
 * 2562 bytes or more, which is nearly twice what fits. An image between the
 * two writes past the buffer. The loader therefore refuses anything whose
 * line exceeds (2562 - 32) / 2 == 1265 bytes, before decode() is called.
 *
 * Both sides of the boundary are checked for two pixel types: one which trips
 * early, truecolor with alpha at 4 bytes per pixel, and one which trips late,
 * 8 bit indexed at 1 byte per pixel.
 *
 * The images beyond the limit deliberately carry no image data at all. The
 * loader rejects them from their header, so even a regression of the limit
 * could not make this test run the overflowing path.
 */
static void testPngImgLoaderLineBufferLimit()
{
    PngImgLoader       loader;
    YAGfxDynamicBitmap bitmap;
    FS                 fileSystem;
    uint16_t           x;
    uint8_t            raw[1U + 1266U * 4U];

    /* Truecolor with alpha: 4 bytes per pixel, so the last width which fits
     * is 1265 / 4 == 316.
     */
    const uint16_t RGBA_WIDTH_OK      = 316U;
    const uint16_t RGBA_WIDTH_TOO_BIG = 317U;

    /* Indexed with 8 bit samples: 1 byte per pixel. */
    const uint16_t IDX_WIDTH_OK       = 1265U;
    const uint16_t IDX_WIDTH_TOO_BIG  = 1266U;

    /* clang-format off */
    const uint8_t      palette[] = {
        0xFFU, 0x00U, 0x00U, /* 0: red */
        0x00U, 0x00U, 0xFFU  /* 1: blue */
    };
    /* clang-format on */

    PngSpec spec;

    /* Just below the limit, truecolor with alpha. Every pixel opaque red. */
    raw[0U] = 0U; /* Filter type: none. */

    for (x = 0U; x < RGBA_WIDTH_OK; ++x)
    {
        uint8_t* pixel = &raw[1U + x * 4U];

        pixel[0U]      = 0xFFU;
        pixel[1U]      = 0x00U;
        pixel[2U]      = 0x00U;
        pixel[3U]      = 0xFFU;
    }

    spec = { RGBA_WIDTH_OK, 1U, 8U, PNG_COLOR_TYPE_RGBA, nullptr, 0U, nullptr, 0U, raw, 1U + RGBA_WIDTH_OK * 4U };

    TEST_ASSERT_TRUE(writePngFile(FILE_NAME_GENERATED, spec));
    TEST_ASSERT_EQUAL(PngImgLoader::RET_OK, loader.load(fileSystem, FILE_NAME_GENERATED, bitmap));
    TEST_ASSERT_EQUAL_UINT16(RGBA_WIDTH_OK, bitmap.getWidth());
    TEST_ASSERT_EQUAL_UINT32(0xFF0000U, static_cast<uint32_t>(bitmap.getColor(0, 0)));
    TEST_ASSERT_EQUAL_UINT32(0xFF0000U, static_cast<uint32_t>(bitmap.getColor(static_cast<int16_t>(RGBA_WIDTH_OK - 1U), 0)));

    /* One pixel wider, no image data. */
    bitmap.release();
    spec = { RGBA_WIDTH_TOO_BIG, 1U, 8U, PNG_COLOR_TYPE_RGBA, nullptr, 0U, nullptr, 0U, nullptr, 0U };

    TEST_ASSERT_TRUE(writePngFile(FILE_NAME_GENERATED, spec));
    TEST_ASSERT_EQUAL(PngImgLoader::RET_IMG_TOO_BIG, loader.load(fileSystem, FILE_NAME_GENERATED, bitmap));
    TEST_ASSERT_FALSE(bitmap.isAllocated());

    /* Just below the limit, 8 bit indexed. The indices alternate, so an
     * off-by-one in the line length would show up as the wrong color.
     */
    raw[0U] = 0U;

    for (x = 0U; x < IDX_WIDTH_OK; ++x)
    {
        raw[1U + x] = static_cast<uint8_t>(x & 0x01U);
    }

    spec = { IDX_WIDTH_OK, 1U, 8U, PNG_COLOR_TYPE_INDEXED, palette, sizeof(palette), nullptr, 0U, raw, 1U + IDX_WIDTH_OK };

    TEST_ASSERT_TRUE(writePngFile(FILE_NAME_GENERATED, spec));
    TEST_ASSERT_EQUAL(PngImgLoader::RET_OK, loader.load(fileSystem, FILE_NAME_GENERATED, bitmap));
    TEST_ASSERT_EQUAL_UINT16(IDX_WIDTH_OK, bitmap.getWidth());
    TEST_ASSERT_EQUAL_UINT32(0xFF0000U, static_cast<uint32_t>(bitmap.getColor(0, 0)));
    TEST_ASSERT_EQUAL_UINT32(0x0000FFU, static_cast<uint32_t>(bitmap.getColor(1, 0)));
    TEST_ASSERT_EQUAL_UINT32(0xFF0000U, static_cast<uint32_t>(bitmap.getColor(static_cast<int16_t>(IDX_WIDTH_OK - 1U), 0)));

    /* One pixel wider, no image data. */
    bitmap.release();
    spec = { IDX_WIDTH_TOO_BIG, 1U, 8U, PNG_COLOR_TYPE_INDEXED, palette, sizeof(palette), nullptr, 0U, nullptr, 0U };

    TEST_ASSERT_TRUE(writePngFile(FILE_NAME_GENERATED, spec));
    TEST_ASSERT_EQUAL(PngImgLoader::RET_IMG_TOO_BIG, loader.load(fileSystem, FILE_NAME_GENERATED, bitmap));
    TEST_ASSERT_FALSE(bitmap.isAllocated());

    (void)remove(FILE_NAME_GENERATED);
}

/**
 * Copy at most the given number of bytes from one file to another one.
 *
 * @param[in] srcFileName   Name of the source file.
 * @param[in] dstFileName   Name of the destination file.
 * @param[in] maxSize       Max. number of bytes to copy.
 *
 * @return If successful, it will return true otherwise false.
 */
static bool copyFilePart(const char* srcFileName, const char* dstFileName, size_t maxSize)
{
    bool  isSuccessful = false;
    FILE* src          = fopen(srcFileName, "rb");

    if (nullptr != src)
    {
        FILE* dst = fopen(dstFileName, "wb");

        if (nullptr != dst)
        {
            size_t  remaining = maxSize;
            uint8_t buffer[64U];

            isSuccessful = true;

            while ((0U < remaining) && (true == isSuccessful))
            {
                const size_t chunkSize = (sizeof(buffer) < remaining) ? sizeof(buffer) : remaining;
                const size_t readSize  = fread(buffer, 1U, chunkSize, src);

                if ((0U == readSize) ||
                    (readSize != fwrite(buffer, 1U, readSize, dst)))
                {
                    isSuccessful = false;
                }
                else
                {
                    remaining -= readSize;
                }
            }

            (void)fclose(dst);
        }

        (void)fclose(src);
    }

    return isSuccessful;
}

/**
 * Get the size of a file in bytes.
 *
 * @param[in] fileName  Name of the file.
 * @param[out] size     Size of the file in bytes.
 *
 * @return If successful, it will return true otherwise false.
 */
static bool getFileSize(const char* fileName, size_t& size)
{
    bool  isSuccessful = false;
    FILE* fd           = fopen(fileName, "rb");

    if (nullptr != fd)
    {
        if (0 == fseek(fd, 0, SEEK_END))
        {
            const long pos = ftell(fd);

            if (0 < pos)
            {
                size         = static_cast<size_t>(pos);
                isSuccessful = true;
            }
        }

        (void)fclose(fd);
    }

    return isSuccessful;
}

/**
 * Write the given bytes to a file, replacing any existing one.
 *
 * @param[in] fileName  Name of the destination file.
 * @param[in] data      Bytes to write. Must not be nullptr.
 * @param[in] size      Number of bytes to write.
 *
 * @return If successful, it will return true otherwise false.
 */
static bool writeFile(const char* fileName, const uint8_t* data, size_t size)
{
    bool  isSuccessful = false;
    FILE* fd           = fopen(fileName, "wb");

    if (nullptr != fd)
    {
        if (size == fwrite(data, 1U, size, fd))
        {
            isSuccessful = true;
        }

        (void)fclose(fd);
    }

    return isSuccessful;
}

/**
 * Write a PNG file according to the given specification.
 *
 * The image data is deflated with stored blocks only, which keeps the test
 * free of any compressor and is still a valid zlib stream.
 *
 * @param[in] fileName  Name of the destination file.
 * @param[in] spec      Specification of the PNG file.
 *
 * @return If successful, it will return true otherwise false.
 */
static bool writePngFile(const char* fileName, const PngSpec& spec)
{
    bool    isSuccessful = true;
    uint8_t buffer[PNG_BUFFER_SIZE];
    uint8_t ihdr[PNG_IHDR_PAYLOAD_SIZE];
    size_t  offset = sizeof(PNG_SIGNATURE);

    memcpy(buffer, PNG_SIGNATURE, sizeof(PNG_SIGNATURE));

    writeUInt32Be(&ihdr[0U], spec.width);
    writeUInt32Be(&ihdr[4U], spec.height);
    ihdr[8U]  = spec.bitDepth;
    ihdr[9U]  = spec.colorType;
    ihdr[10U] = 0U; /* Compression method: deflate. */
    ihdr[11U] = 0U; /* Filter method: adaptive. */
    ihdr[12U] = 0U; /* Interlace method: none. */

    if (false == appendChunk(buffer, sizeof(buffer), offset, "IHDR", ihdr, sizeof(ihdr)))
    {
        isSuccessful = false;
    }

    if ((true == isSuccessful) &&
        (nullptr != spec.palette))
    {
        isSuccessful = appendChunk(buffer, sizeof(buffer), offset, "PLTE", spec.palette, spec.paletteSize);
    }

    if ((true == isSuccessful) &&
        (nullptr != spec.trns))
    {
        isSuccessful = appendChunk(buffer, sizeof(buffer), offset, "tRNS", spec.trns, spec.trnsSize);
    }

    if ((true == isSuccessful) &&
        (nullptr != spec.raw))
    {
        isSuccessful = appendIdatChunk(buffer, sizeof(buffer), offset, spec.raw, spec.rawSize);
    }

    if (true == isSuccessful)
    {
        isSuccessful = appendChunk(buffer, sizeof(buffer), offset, "IEND", nullptr, 0U);
    }

    if (true == isSuccessful)
    {
        isSuccessful = writeFile(fileName, buffer, offset);
    }

    return isSuccessful;
}

/**
 * Append a PNG chunk, consisting of its length, type, payload and CRC.
 *
 * @param[in] buffer        Destination buffer.
 * @param[in] bufferSize    Size of the destination buffer in bytes.
 * @param[in,out] offset    Current write position in the destination buffer.
 * @param[in] type          Chunk type, 4 characters.
 * @param[in] payload       Chunk payload. May be nullptr for an empty chunk.
 * @param[in] payloadSize   Size of the chunk payload in bytes.
 *
 * @return If successful, it will return true otherwise false.
 */
static bool appendChunk(uint8_t* buffer, size_t bufferSize, size_t& offset, const char* type, const uint8_t* payload, size_t payloadSize)
{
    bool         isSuccessful = false;
    const size_t chunkSize    = PNG_CHUNK_OVERHEAD + payloadSize;

    if (bufferSize >= (offset + chunkSize))
    {
        uint8_t* chunk = &buffer[offset];

        writeUInt32Be(&chunk[0U], static_cast<uint32_t>(payloadSize));
        memcpy(&chunk[4U], type, 4U);

        if (0U < payloadSize)
        {
            memcpy(&chunk[8U], payload, payloadSize);
        }

        /* The CRC covers the chunk type and the chunk payload. */
        writeUInt32Be(&chunk[8U + payloadSize], calcCrc32(&chunk[4U], 4U + payloadSize));

        offset       += chunkSize;
        isSuccessful  = true;
    }

    return isSuccessful;
}

/**
 * Append an IDAT chunk, which carries the raw image data as a zlib stream
 * built from stored deflate blocks.
 *
 * @param[in] buffer        Destination buffer.
 * @param[in] bufferSize    Size of the destination buffer in bytes.
 * @param[in,out] offset    Current write position in the destination buffer.
 * @param[in] raw           Raw image data. Must not be nullptr.
 * @param[in] rawSize       Size of the raw image data in bytes.
 *
 * @return If successful, it will return true otherwise false.
 */
static bool appendIdatChunk(uint8_t* buffer, size_t bufferSize, size_t& offset, const uint8_t* raw, size_t rawSize)
{
    bool         isSuccessful = false;
    uint8_t      zlibStream[PNG_BUFFER_SIZE];
    const size_t zlibSize = 2U + 5U + rawSize + 4U;

    /* One stored block is enough, because the test images are small. */
    if ((sizeof(zlibStream) >= zlibSize) &&
        (0xFFFFU >= rawSize))
    {
        const uint32_t adler = calcAdler32(raw, rawSize);

        zlibStream[0U]       = 0x78U; /* Deflate, 32 kByte window. */
        zlibStream[1U]       = 0x01U; /* No preset dictionary, fastest level. */
        zlibStream[2U]       = 0x01U; /* Final block, stored. */
        zlibStream[3U]       = static_cast<uint8_t>(rawSize & 0xFFU);
        zlibStream[4U]       = static_cast<uint8_t>((rawSize >> 8U) & 0xFFU);
        zlibStream[5U]       = static_cast<uint8_t>((~rawSize) & 0xFFU);
        zlibStream[6U]       = static_cast<uint8_t>(((~rawSize) >> 8U) & 0xFFU);

        memcpy(&zlibStream[7U], raw, rawSize);
        writeUInt32Be(&zlibStream[7U + rawSize], adler);

        isSuccessful = appendChunk(buffer, bufferSize, offset, "IDAT", zlibStream, zlibSize);
    }

    return isSuccessful;
}

/**
 * Write a 32 bit value in network byte order.
 *
 * @param[out] buffer   Destination buffer, at least 4 bytes.
 * @param[in] value     Value to write.
 */
static void writeUInt32Be(uint8_t* buffer, uint32_t value)
{
    buffer[0U] = static_cast<uint8_t>((value >> 24U) & 0xFFU);
    buffer[1U] = static_cast<uint8_t>((value >> 16U) & 0xFFU);
    buffer[2U] = static_cast<uint8_t>((value >> 8U) & 0xFFU);
    buffer[3U] = static_cast<uint8_t>(value & 0xFFU);
}

/**
 * Calculate the CRC-32 checksum which PNG uses for its chunks.
 *
 * @param[in] data  Data to calculate the checksum of. Must not be nullptr.
 * @param[in] size  Size of the data in bytes.
 *
 * @return CRC-32 checksum
 */
static uint32_t calcCrc32(const uint8_t* data, size_t size)
{
    uint32_t crc = 0xFFFFFFFFU;
    size_t   idx;

    /* Reversed representation of the CRC-32 polynomial. */
    const uint32_t POLYNOMIAL = 0xEDB88320U;

    for (idx = 0U; idx < size; ++idx)
    {
        uint8_t bit;

        crc ^= static_cast<uint32_t>(data[idx]);

        for (bit = 0U; bit < 8U; ++bit)
        {
            if (0U != (crc & 1U))
            {
                crc = (crc >> 1U) ^ POLYNOMIAL;
            }
            else
            {
                crc >>= 1U;
            }
        }
    }

    return crc ^ 0xFFFFFFFFU;
}

/**
 * Calculate the Adler-32 checksum which the zlib stream is terminated with.
 *
 * @param[in] data  Data to calculate the checksum of. Must not be nullptr.
 * @param[in] size  Size of the data in bytes.
 *
 * @return Adler-32 checksum
 */
static uint32_t calcAdler32(const uint8_t* data, size_t size)
{
    uint32_t sumLow  = 1U;
    uint32_t sumHigh = 0U;
    size_t   idx;

    /* Largest prime which is smaller than 65536. */
    const uint32_t MODULO = 65521U;

    for (idx = 0U; idx < size; ++idx)
    {
        sumLow  = (sumLow + static_cast<uint32_t>(data[idx])) % MODULO;
        sumHigh = (sumHigh + sumLow) % MODULO;
    }

    return (sumHigh << 16U) | sumLow;
}
